"""Generate the MSP430's simulated tether sweep table from the CSV files.

The festival firmware has no real tether instrument yet, so it transmits
simulated sweeps baked into FRAM. This script writes them as C source:

    platform/tether_sim_data.h
    platform/tether_sim_data.c

It uses the same CSV selection as simulator.py (I_endpoint, rows 1, 3, ..., 99),
then stores each current as a signed 32-bit integer in units of 1e-10 A,
i.e. microamps to 4 decimal places (12.3456 uA -> 123456). The simulated
range is about +/-2010 uA = +/-2.01e7 units, well inside int32.

The ground decoder multiplies by 10**7 to get back to readings.txt's 1e-17 A
units, so the viewer receives these values rounded to 1e-10 A.

Run from this directory, then commit the two generated files:

    python export_sweeps_c.py            # first 10 CSVs
    python export_sweeps_c.py --count 20
"""

import argparse
from decimal import Decimal, ROUND_HALF_EVEN
from pathlib import Path

from reader import SAMPLE_COUNT
from simulator import extract_currents, find_default_source

# readings.txt / simulator.py use 1e-17 A; the radio uses 1e-10 A.
SCALE_DOWN = 10**7
INT32_MIN, INT32_MAX = -(2**31), 2**31 - 1

DEFAULT_OUT_DIR = Path(__file__).resolve().parent.parent.parent / "platform"


def to_radio_units(current_1e17: int) -> int:
    """1e-17 A integer -> 1e-10 A integer, rounding half to even."""
    value = int((Decimal(current_1e17) / SCALE_DOWN).to_integral_value(rounding=ROUND_HALF_EVEN))
    if not INT32_MIN <= value <= INT32_MAX:
        raise ValueError(f"current {current_1e17} does not fit in int32 after scaling")
    return value


def write_header(path: Path, count: int) -> None:
    path.write_text(f"""\
/**
 * @file   tether_sim_data.h
 * @brief  Simulated tether I-V sweeps transmitted by the festival demo.
 *
 * GENERATED by ground/iv_viewer/export_sweeps_c.py - do not edit by hand.
 */

#ifndef TETHER_SIM_DATA_H
#define TETHER_SIM_DATA_H

#include <stdint.h>

/* Currents per sweep (CSV rows 1, 3, ..., 99 of the 100-point voltage sweep). */
#define TETHER_SIM_SAMPLES      {SAMPLE_COUNT}U

/* Number of sweeps in the table. The demo cycles through them in order. */
#define TETHER_SIM_SWEEP_COUNT  {count}U

/* Currents in units of 1e-10 A (microamps x 10^4). Stored in FRAM. */
extern const int32_t tether_sim_sweeps[TETHER_SIM_SWEEP_COUNT][TETHER_SIM_SAMPLES];

#endif /* TETHER_SIM_DATA_H */
""", encoding="utf-8", newline="\n")


def write_source(path: Path, csv_files: list[Path], sweeps: list[list[int]]) -> None:
    lines = [
        "/* GENERATED by ground/iv_viewer/export_sweeps_c.py - do not edit by hand.",
        " * Units: 1e-10 A (microamps x 10^4). */",
        "",
        '#include "tether_sim_data.h"',
        "",
        "const int32_t tether_sim_sweeps[TETHER_SIM_SWEEP_COUNT][TETHER_SIM_SAMPLES] =",
        "{",
    ]
    for index, (csv_path, sweep) in enumerate(zip(csv_files, sweeps)):
        lines.append(f"    /* {index}: {csv_path.name} */")
        lines.append("    {")
        for start in range(0, len(sweep), 5):
            chunk = ", ".join(f"{value:>10}L" for value in sweep[start:start + 5])
            lines.append(f"        {chunk},")
        lines.append("    },")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source-dir", type=Path, default=find_default_source())
    parser.add_argument("--count", type=int, default=10)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()
    if not 1 <= args.count <= 600:
        parser.error("--count must be between 1 and 600")

    csv_files = sorted(args.source_dir.glob("*.csv"))[:args.count]
    if len(csv_files) < args.count:
        parser.error(f"only {len(csv_files)} CSV files in {args.source_dir}")

    sweeps = [[to_radio_units(c) for c in extract_currents(p)] for p in csv_files]

    write_header(args.out_dir / "tether_sim_data.h", args.count)
    write_source(args.out_dir / "tether_sim_data.c", csv_files, sweeps)
    print(f"Wrote {args.count} sweeps x {SAMPLE_COUNT} currents "
          f"({args.count * SAMPLE_COUNT * 4} bytes) to {args.out_dir}")


if __name__ == "__main__":
    main()
